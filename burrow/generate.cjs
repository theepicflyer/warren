#!/usr/bin/env node
/*
 * Builds warren/burrow from Burrow's export in burrow/export/ (the design-system artifact's own files,
 * copied as they are; see burrow/README.md). No dependencies:
 *
 *   node burrow/generate.cjs
 *
 * Writes, under src/burrow/generated/ (all generated, never hand-edited):
 *   tokens.css   the tokens as CSS variables: light by default, dark with the device or with
 *                html[data-theme="dark"]; html[data-theme="light"] keeps light
 *   type.css     the text styles as classes (.hero-number, .page-title, .card-title, .body, ...)
 *   burrow.css   the bh-* component classes (bundle.css without its Google Fonts import)
 *   art.js       the bundle's SVG string generators as an ES module, without its React components
 *   art.d.ts     types for art.js, with the names (animals, moods, traces, icons...) read from it
 *   scenes.ts    the drawings that change with a count (a fund's stash, the month's wreath)
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const HERE = __dirname;
const EXPORT = path.join(HERE, 'export');
const OUT = process.env.BURROW_OUT ? path.resolve(process.env.BURROW_OUT) : path.resolve(HERE, '../src/burrow/generated');
const read = (rel) => fs.readFileSync(path.join(EXPORT, rel), 'utf8');
const out = (name, text) => {
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, name), text);
};
const banner = (from) => `GENERATED by burrow/generate.cjs from Burrow's ${from}. Do not edit; re-sync instead (burrow/README.md).`;

/* ---------- tokens.css and type.css ---------- */
const tokens = JSON.parse(read('tokens.json'));
const themeIds = tokens.color.themes.map((t) => t.id);
if (themeIds[0] !== 'light' || !themeIds.includes('dark')) throw new Error(`tokens.json: expected themes light (first) and dark, got ${themeIds}`);
const valueIn = (v, theme) => {
  if (v && typeof v === 'object') v = v[theme] ?? v[themeIds[0]];
  const alias = /^\{([\w.-]+)\}$/.exec(v);
  return alias ? `var(--${alias[1]})` : v;
};
const colours = [...tokens.color.tokens, ...(tokens.shadow?.tokens ?? [])];
// A token with one value in every theme is set once; the rest are set per theme.
const same = colours.filter((t) => valueIn(t.value, 'light') === valueIn(t.value, 'dark'));
const themed = colours.filter((t) => !same.includes(t));
const decl = (t, theme) => `\t--${t.name}: ${valueIn(t.value, theme)};`;
const fixed = ['spacing', 'radius', 'border'].flatMap((family) => (tokens[family]?.tokens ?? []).map((t) => `\t--${t.name}: ${t.value};`));
for (const [name, stack] of Object.entries(tokens.type.families)) fixed.push(`\t--font-${name}: ${stack};`);
const indent = (lines) => lines.map((l) => '\t' + l).join('\n');
const lightLines = themed.map((t) => decl(t, 'light'));
const darkLines = themed.map((t) => decl(t, 'dark'));
out('tokens.css', `/* ${banner('tokens.json')}
   The app re-points --accent and --accent-soft to its home colour after importing this, if it isn't tomato. */
:root {
${fixed.join('\n')}
${same.map((t) => decl(t, 'light')).join('\n')}
}

:root {
\tcolor-scheme: light;
${lightLines.join('\n')}
}

@media (prefers-color-scheme: dark) {
\t:root:not([data-theme='light']) {
\t\tcolor-scheme: dark;
${indent(darkLines)}
\t}
}

:root[data-theme='dark'] {
\tcolor-scheme: dark;
${darkLines.join('\n')}
}
`);

const css = (o) => Object.entries(o).map(([k, v]) => `${k}: ${v};`).join(' ');
const typeRules = tokens.type.groups.flatMap((g) =>
  g.styles.map((s) => `.${s.name} { ${css({
    'font-family': `var(--font-${g.family})`,
    'font-size': s.fontSize,
    'line-height': s.lineHeight,
    'font-weight': s.fontWeight,
    ...(s.letterSpacing ? { 'letter-spacing': s.letterSpacing } : {}),
  })} }`));
out('type.css', `/* ${banner('tokens.json')} */\n${typeRules.join('\n')}\n`);

/* ---------- burrow.css ---------- */
const bundleCss = read('components/bundle.css');
const fontImport = /^@import url\([^)]*fonts\.googleapis[^)]*\);\s*/m;
if (!fontImport.test(bundleCss)) console.warn('bundle.css: no Google Fonts import to drop; check the export.');
out('burrow.css', `/* ${banner('components/bundle.css')}
   As exported, minus its Google Fonts import: the apps bundle their fonts. */
${bundleCss.replace(fontImport, '')}`);

/* ---------- art.js: the bundle's string generators as a module ---------- */
const bundle = read('components/bundle.js');
const meta = JSON.parse(/^\/\* @ds-bundle: (\{.*\}) \*\/$/m.exec(bundle)[1]);
const COMPONENTS = new Set(meta.components.map((c) => c.name));
const open = '(function () {\n', close = '\n})();';
const start = bundle.indexOf(open), end = bundle.lastIndexOf(close);
if (start < 0 || end < 0) throw new Error('bundle.js: expected one (function () { ... })(); around the code');
const body = bundle.slice(start + open.length, end).split('\n').map((l) => l.replace(/^ {2}/, ''));

// Top-level statements start in the first column; the lines after one, indented or a closing
// bracket, belong to it. Comments and blank lines stand alone.
const chunks = [];
for (const line of body) {
  const startsStatement = /^[^\s})\]]/.test(line) || line.trim() === '' || /^\/\*.*\*\/\s*$/.test(line);
  if (startsStatement || !chunks.length) chunks.push([line]);
  else chunks[chunks.length - 1].push(line);
}
const text = (c) => c.join('\n');
const usesReact = (s) => /(^|[^\w$.])(h|React)\b/.test(s.replace(/'[^'\n]*'|"[^"\n]*"/g, "''"));
const isComponent = (s) => {
  const fn = /^function (\w+)\(/.exec(s);
  return fn && COMPONENTS.has(fn[1]);
};
const dropped = [];
const kept = [];
for (let i = 0; i < chunks.length; i++) {
  const s = text(chunks[i]);
  const drop = isComponent(s) || usesReact(s) || /^window\.\w+\s*=/.test(s);
  if (!drop) {
    kept.push(chunks[i]);
    continue;
  }
  dropped.push((/^(?:function|var) (\w+)|^(window\.\w+)/.exec(s) || []).slice(1).find(Boolean) ?? s.slice(0, 30));
  // a comment just above a dropped component describes it
  while (kept.length && /^\/\*/.test(text(kept[kept.length - 1])) && !/^\/\* -{3,}/.test(text(kept[kept.length - 1]))) kept.pop();
}
// what is left must not need React, and every name it declares is exported
// a section heading with nothing left under it goes too
const heading = (c) => /^\/\* -{3,}/.test(text(c));
const filled = kept.filter((c, i) => {
  if (!heading(c)) return true;
  const next = kept.slice(i + 1).find((d) => text(d).trim() !== '');
  return next && !heading(next);
});
const code = filled.map(text).join('\n').replace(/\n{3,}/g, '\n\n').trim();
if (usesReact(code)) throw new Error('art.js: something left still uses React');
const ctx = vm.createContext({});
vm.runInContext(code, ctx);
const names = Object.keys(ctx);
const A = ctx;
// Draw everything once, so a generator that still needs something dropped fails here, not in an app.
for (const who of [...Object.keys(A.NAMES), ...Object.keys(A.ALIAS)]) for (const mood of A.MOODS) A.mascotSVG(who, mood);
for (const t of Object.keys(A.TRACES)) A.traceSVG(t, 32);
for (const kind of Object.keys(A.TRAIL)) A.trailSVG({ kind, points: [[0, 0], [100, 60], [200, 20]], width: 200, height: 60 });
for (const hab of Object.values(A.HAB)) hab.props();
A.worldSVG();
for (const who of Object.keys(A.NAMES)) A.pawsSVG(who, 2, 72);
out('art.js', `// @ts-nocheck
/* ${banner('components/bundle.js')}
   The bundle's code as it is, without the IIFE around it and without its React components
   (${[...COMPONENTS].join(', ')}), so the Svelte components can draw the same art. */
${code}

export {
${names.join(', ')}
};
`);

/* ---------- art.d.ts, with the names read from the art itself ---------- */
const union = (keys) => keys.map((k) => `'${k}'`).join(' | ');
const animals = Object.keys(A.NAMES);
const hosts = Object.keys(A.ALIAS);
out('art.d.ts', `/* ${banner('components/bundle.js')} Types for art.js. */

export type Animal = ${union(animals)};
export type Character = ${union(hosts)} | Animal;
export type Mood = ${union(A.MOODS)};
export type TraceName = ${union(Object.keys(A.TRACES))};
export type TrailKind = ${union(Object.keys(A.TRAIL))};
export type HabitatKind = ${union(Object.keys(A.HAB))};
export type IconName = ${union(Object.keys(A.ICONS))};

export interface TrailOptions {
	kind: TrailKind;
	points: [number, number][];
	width: number;
	height: number;
	spacing?: number;
	/** 0..1: how strong the trail starts */
	fade?: number;
	/** 0..1: the share drawn at full strength */
	done?: number;
}

export interface TrailPoint {
	x: number;
	y: number;
	/** heading in degrees */
	a: number;
}

export interface Habitat {
	who: Animal;
	props: () => string;
	ground: string;
	far: string;
}

export const INK: string;
export const C: Record<string, string>;
export const NAMES: Record<Animal, string>;
export const ALIAS: Record<${union(hosts)}, Animal>;
export const MOODS: Mood[];
export const FUR: Record<Animal, string>;
export const CAST: Record<Animal, (mood?: Mood) => string>;
export const TRACES: Record<TraceName, () => string>;
export const TRACE_OWNER: Record<TraceName, Character>;
export const TRAIL: Record<TrailKind, { spacing: number; draw: (p: TrailPoint, i: number, op: number | string) => string }>;
export const HAB: Record<HabitatKind, Habitat>;
export const ICONS: Record<IconName, string>;
export const STEP_MARK: Record<TrailKind, TraceName>;

/** One animal in a mood, as an SVG string (120 × 120 view box). */
export function mascotSVG(character: Character, mood?: Mood, label?: string): string;
/** A trace as an SVG string. */
export function traceSVG(name: TraceName, size?: number): string;
/** Traces along a smooth path through the points. */
export function trailSVG(opts: TrailOptions): string;
/** All four habitats in one landscape. */
export function worldSVG(): string;
export function pawsSVG(who: Animal, n: 1 | 2, size: number): string;
/** Points every \`spacing\` along a smooth path, with their heading. */
export function along(points: [number, number][], spacing: number): TrailPoint[];
export function printAt(x: number, y: number, s?: number, rot?: number, fill?: string, op?: string | number): string;
export function acornAt(x: number, y: number, s?: number, rot?: number): string;
export function seedAt(x: number, y: number, s?: number, rot?: number): string;
export function leafAt(x: number, y: number, s?: number, rot?: number, fill?: string): string;
export function crumb(x: number, y: number, s?: number, rot?: number): string;
export function cloud(x: number, y: number, s: number): string;
export function tr(name: TraceName, x: number, y: number, s?: number, rot?: number): string;
/** "Wed 22 Oct", with the year when it isn't now's. */
export function formatDay(date: Date, now?: Date): string;
`);

/* ---------- scenes.ts: render the bundle's Stash and Ring with a tiny string renderer for React ---------- */
const ATTR = { className: 'class', strokeWidth: 'stroke-width', strokeLinecap: 'stroke-linecap', strokeLinejoin: 'stroke-linejoin', strokeDasharray: 'stroke-dasharray', strokeDashoffset: 'stroke-dashoffset' };
const UNITLESS = new Set(['opacity', 'zIndex', 'flex', 'fontWeight', 'lineHeight']);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const styleStr = (o) => Object.entries(o).filter(([, v]) => v != null && v !== '')
  .map(([k, v]) => k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase()) + ':' + (typeof v === 'number' && !UNITLESS.has(k) ? v + 'px' : v)).join(';');
const h = (type, props, ...children) => ({ type, props: props || {}, children });
function render(n) {
  if (n == null || n === false || n === true) return '';
  if (Array.isArray(n)) return n.map(render).join('');
  if (typeof n === 'string' || typeof n === 'number') return esc(n);
  if (typeof n.type === 'function') {
    const kids = n.children.length === 1 ? n.children[0] : n.children.length ? n.children : n.props.children;
    return render(n.type(Object.assign({}, n.props, { children: kids })));
  }
  let a = '';
  for (const [k, v] of Object.entries(n.props)) {
    if (['children', 'dangerouslySetInnerHTML', 'key', 'ref'].includes(k) || v == null || v === false || typeof v === 'function') continue;
    if (k === 'style') { const s = styleStr(v); if (s) a += ' style="' + esc(s) + '"'; continue; }
    a += ' ' + (ATTR[k] || k) + '="' + esc(v === true ? '' : v) + '"';
  }
  const inner = n.props.dangerouslySetInnerHTML ? n.props.dangerouslySetInnerHTML.__html : render(n.children.length ? n.children : n.props.children);
  return '<' + n.type + a + '>' + inner + '</' + n.type + '>';
}
const React = { createElement: h, Fragment: 'frag', useState: (v) => [typeof v === 'function' ? v() : v, () => {}], useEffect: () => {}, useLayoutEffect: () => {}, useRef: (v) => ({ current: v }), useMemo: (f) => f(), useCallback: (f) => f };
const win = { React };
new Function('window', bundle)(win);
const B = win[meta.namespace];

const lit = (s) => `\ts += ${JSON.stringify(s)};\n`;
const when = (cond, s) => `\tif (${cond}) {\n${lit(s).replace(/^\t/, '\t\t')}\t}\n`;

// Stash: 15 acorn slots; slot k shows when acorns >= k.
const stashSvg = (v) => render(h(B.Stash, { name: '', value: v, max: 15, valueText: '' })).match(/<svg[\s\S]*<\/svg>/)[0];
const empty = stashSvg(0), full = stashSvg(15);
const footAt = empty.indexOf('<g transform="translate(64 80)">');
const foot = empty.slice(footAt, empty.lastIndexOf('</svg>'));
const base = empty.slice(0, footAt);
if (footAt < 0 || !full.startsWith(base)) throw new Error('Stash: unexpected markup');
let stash = lit(base);
for (let k = 1; k <= 15; k++) {
  const prev = stashSvg(k - 1).replace(foot, ''), cur = stashSvg(k);
  stash += when(`acorns >= ${k}`, cur.slice(prev.length - '</svg>'.length, cur.length - '</svg>'.length));
}
stash += when('acorns <= 0', foot) + lit('</svg>');

// Wreath ring: 26 oak leaves; leaf i is lit when leaves > i. Everything inside the ring but its centre.
const ring = render(h(B.Ring, { value: 0, max: 1, variant: 'wreath', size: 196 }, '@@CENTER@@'));
const art = ring.slice(ring.indexOf('>') + 1, ring.indexOf('<div class="bh-ring__center"'));
const parts = art.split('class="bh-wleaf');
if (parts.length !== 27) throw new Error(`Ring wreath: expected 26 leaves, found ${parts.length - 1}`);
let wreath = lit(parts[0]);
parts.slice(1).forEach((part, i) => (wreath += lit('class="bh-wleaf') + when(`leaves > ${i}`, ' is-on') + lit(part)));

out('scenes.ts', `// ${banner('components/bundle.js')}

/** A sinking fund's buried store (Burrow's Stash), with 0 to 15 acorns (round(share * 15)). */
export function stashArt(acorns: number): string {
\tlet s = '';
${stash}\treturn s;
}

/** The month's oak wreath (Burrow's Ring, wreath variant, 196px) with 0 to 26 leaves lit (round(share * 26)):
    everything inside the ring except its centre. */
export function wreathArt(leaves: number): string {
\tlet s = '';
${wreath}\treturn s;
}
`);

console.log(`Burrow regenerated into ${path.relative(process.cwd(), OUT) || '.'}: ${names.length} names in art.js, dropped ${dropped.join(', ')}.`);
